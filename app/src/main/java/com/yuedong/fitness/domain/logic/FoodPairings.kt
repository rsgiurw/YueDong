    /** 获取常见搭配：手写优先，模板兜底 */
    fun pairingOf(food: Food): String {
        handWritten[food.name]?.let { return it }
        val tpl = categoryTemplate[food.category] ?: return ""
        return tpl.replace("{name}", food.name)
    }
